USE ajira_v4;

CREATE TABLE IF NOT EXISTS club_files (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  title VARCHAR(160) NOT NULL,
  description VARCHAR(1000) DEFAULT NULL,
  original_name VARCHAR(255) NOT NULL,
  folder_path VARCHAR(1000) NOT NULL DEFAULT '',
  stored_name VARCHAR(64) NOT NULL UNIQUE,
  mime_type VARCHAR(100) NOT NULL,
  file_size INT UNSIGNED NOT NULL,
  share_token CHAR(64) DEFAULT NULL UNIQUE,
  uploaded_by INT UNSIGNED DEFAULT NULL,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  INDEX idx_club_files_created (created_at),
  CONSTRAINT fk_club_files_admin FOREIGN KEY (uploaded_by) REFERENCES admin_users(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

ALTER TABLE club_files
  ADD COLUMN IF NOT EXISTS folder_path VARCHAR(1000) NOT NULL DEFAULT '' AFTER original_name;

CREATE TABLE IF NOT EXISTS club_folders (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  folder_path VARCHAR(1000) NOT NULL UNIQUE,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
